import { readFile } from 'node:fs/promises'
import { expect, test } from '@playwright/test'

test('overview, date ranges, source trends, and theme persistence', async ({ page }, testInfo) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'A clearer view of your world.' })).toBeVisible()
  await expect(page.getByLabel('Monitoring summary')).toContainText('1,248')
  await page.screenshot({ path: testInfo.outputPath('desktop-light.png'), fullPage: true })
  await page.getByLabel('Date range').selectOption('30d')
  await expect(page.getByLabel('Monitoring summary')).toContainText('4,862')
  await page.getByLabel('Trend source').selectOption('news')
  await expect(page.getByRole('img', { name: /news mentions over/ })).toBeVisible()
  await page.getByRole('button', { name: 'Switch to dark mode' }).click()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  await page.reload()
  await expect(page.getByRole('heading', { name: 'A clearer view of your world.' })).toBeVisible()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  await page.screenshot({ path: testInfo.outputPath('desktop-dark.png'), fullPage: true })
  expect(errors).toEqual([])
})

test('search, sentiment filtering, bookmarks, detail dialogs, and CSV export', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Mentions', exact: true }).click()
  await page.getByLabel('Search mentions').fill('climate')
  await expect(page.locator('.mention')).toHaveCount(2)
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Export', exact: true }).click()
  const download = await downloadPromise
  expect(download.suggestedFilename()).toBe('snowdrop-mentions-demo.csv')
  const csv = await readFile((await download.path())!, 'utf8')
  expect(csv).toContain('Climate-tech startups')
  expect(csv).not.toContain('A quieter revolution')
  await page.getByRole('button', { name: 'Clear search' }).click()
  await page.getByLabel('Filter by sentiment').selectOption('negative')
  await expect(page.locator('.mention')).toHaveCount(1)
  await page.getByRole('button', { name: /^Save mention:/ }).click()
  await page.getByRole('button', { name: 'Beyond the green label: why transparency needs to come first', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await expect(dialog).toBeVisible()
  await expect(dialog.getByRole('link', { name: 'Visit publisher' })).toHaveAttribute('href', 'https://medium.com/')
  await expect(dialog.getByRole('button', { name: 'Saved to your collection' })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
  await page.reload()
  await page.getByRole('button', { name: /Saved mentions/ }).click()
  await expect(page.locator('.mention')).toHaveCount(4)
  await expect(page.getByRole('button', { name: 'Beyond the green label: why transparency needs to come first', exact: true })).toBeVisible()
})

test('mobile navigation and collector configuration stay usable without overflow', async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'A clearer view of your world.' })).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('mobile-light.png'), fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.getByRole('button', { name: 'Open navigation' }).click()
  await expect(page.getByRole('button', { name: 'Close navigation', exact: true })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('button', { name: 'Open navigation' })).toBeFocused()
  await page.getByRole('button', { name: 'Open navigation' }).click()
  await page.getByRole('button', { name: 'Switch to dark mode' }).focus()
  await page.keyboard.press('Tab')
  await expect(page.getByRole('button', { name: 'Snowdrop home' })).toBeFocused()
  await page.getByRole('button', { name: 'Sources', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Your source landscape' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Close navigation', exact: true })).not.toBeVisible()
  await page.getByRole('button', { name: 'Manage source connections' }).click()
  await expect(page.getByRole('heading', { name: 'Bring your listening to life.' })).toBeVisible()
  await page.getByRole('button', { name: 'Add source', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await expect(dialog.getByLabel('Platform')).toBeVisible()
  await dialog.getByLabel('Platform').selectOption('youtube')
  await expect(dialog.getByLabel('Items per run')).toHaveValue('2')
  await expect(dialog.getByLabel('Comments per video')).toBeVisible()
  await page.getByRole('button', { name: 'Close dialog' }).click()
  await page.getByRole('button', { name: 'Open navigation' }).click()
  await page.getByRole('button', { name: 'Switch to dark mode' }).click()
  await page.getByRole('button', { name: 'Overview', exact: true }).click()
  await page.screenshot({ path: testInfo.outputPath('mobile-dark.png'), fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
})

test('API failure explains recovery and retry reconnects the dashboard', async ({ page }) => {
  await page.route('**/api/dashboard', route => route.fulfill({ status: 503, body: 'Unavailable' }))
  await page.goto('/')
  await expect(page.getByRole('alert')).toContainText('Start the Python API on port 8000')
  await page.unroute('**/api/dashboard')
  await page.getByRole('button', { name: 'Try again' }).click()
  await expect(page.getByRole('heading', { name: 'A clearer view of your world.' })).toBeVisible()
})
